def delete_record(entity: str, record_id):
    """Delete one selected record using a strict table allow-list.

    Related trainee records are intentionally not cascaded; PostgreSQL protects
    linked application/mentor/project data and the caller can show a clear error.
    """
    targets = {
        "application": ('Applications', 'ApplicationID'),
        "mentor": ('Mentors', 'MentorID'),
        "project_tracking": ('ProjectTracking', 'ProjectTrackingID'),
        "trainee": ('Trainees', 'TraineeID'),
    }
    if entity not in targets:
        raise DataError('This record type cannot be deleted from the application.')
    if record_id is None:
        raise DataError('Select a record before deleting it.')
    ensure_extended_schema()
    table, key = targets[entity]
    try:
        with _db.connection() as conn:
            with conn.cursor() as cur:
                cur.execute(f'DELETE FROM "{table}" WHERE "{key}"=%s', (record_id,))
                if cur.rowcount == 0:
                    raise DataError('This record no longer exists. Refresh the table and try again.')
    except DataError:
        raise
    except Exception as exc:
        if entity == 'trainee':
            raise DataError('Could not delete this trainee because it may be linked to applications, mentor interviews, or project tracking. Delete or reassign those linked records first.') from exc
        raise DataError(f'Could not delete this record ({exc.__class__.__name__}). Check the database connection and try again.') from exc


def authenticate(username: str, password: str):
    try:
        row = _db.fetch_one('SELECT "Username", "Password", "Role" FROM "Users" WHERE LOWER("Username")=LOWER(%s) LIMIT 1', (username.strip(),))
    except DatabaseError as exc: raise DataError(str(exc)) from exc
    if row and str(row['Password']) == password:
        role = str(row.get('Role') or 'user').strip().lower()
        return row['Username'], ('admin' if role == 'admin' else 'user')
    return None

def register_user(username: str, password: str, role: str = 'user') -> None:
    username = username.strip()
    if not username or not password: raise DataError('Username and password are required.')
    try:
        existing = _db.fetch_one('SELECT "UserID" FROM "Users" WHERE LOWER("Username")=LOWER(%s)', (username,))
        if existing: raise DataError('That username is already taken.')
        _db.execute('INSERT INTO "Users" ("Username","Password","Role") VALUES (%s,%s,%s)', (username,password,'admin' if str(role).lower()=='admin' else 'user'))
    except DatabaseError as exc: raise DataError(str(exc)) from exc

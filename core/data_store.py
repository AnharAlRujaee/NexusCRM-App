def load_admin_contacts() -> list:
    """Return the live participant directory used by the Admin calendar tools.

    Applications and trainee records share the same TraineeID, so the Admin
    workspace always reads the latest name, email and phone from the canonical
    Trainees row rather than copying stale contact details into calendar rows.
    """
    ensure_extended_schema()
    try:
        return _db.fetch_all('''SELECT t."TraineeID" AS trainee_id,
            t."FullName" AS full_name,
            t."EmailAddress" AS email,
            t."PhoneNumber" AS phone,
            COALESCE(MAX(a."CurrentStatus"), '') AS application_status,
            COALESCE(STRING_AGG(DISTINCT m."MentorFullName", ', ') FILTER (WHERE m."MentorFullName" IS NOT NULL AND m."MentorFullName" <> ''), '') AS mentor_names
            FROM "Trainees" t
            LEFT JOIN "Applications" a ON a."TraineeID" = t."TraineeID"
            LEFT JOIN "Mentors" m ON m."TraineeID" = t."TraineeID"
            GROUP BY t."TraineeID", t."FullName", t."EmailAddress", t."PhoneNumber"
            ORDER BY t."FullName"''')
    except DatabaseError as exc:
        raise DataError(str(exc)) from exc


def _v(value):
    if value is None: return None
    value = str(value).strip()
    return value or None

def _trainee_id(cur, name, email=None, phone=None, postal=None, province=None):
    name = _v(name)
    if not name: raise DataError('Full Name is required.')
    email = _v(email)
    if email:
        cur.execute('''INSERT INTO "Trainees" ("FullName","EmailAddress","PhoneNumber","PostalCode","StateOfResidence") VALUES (%s,%s,%s,%s,%s) ON CONFLICT ("EmailAddress") DO UPDATE SET "FullName"=EXCLUDED."FullName", "PhoneNumber"=EXCLUDED."PhoneNumber", "PostalCode"=EXCLUDED."PostalCode", "StateOfResidence"=EXCLUDED."StateOfResidence" RETURNING "TraineeID"''', (name,email,_v(phone),_v(postal),_v(province)))
    else:
        cur.execute('INSERT INTO "Trainees" ("FullName","PhoneNumber","PostalCode","StateOfResidence") VALUES (%s,%s,%s,%s) RETURNING "TraineeID"', (name,_v(phone),_v(postal),_v(province)))
    return cur.fetchone()[0]


def save_application(data, record_id=None):
    ensure_extended_schema()
    try:
        with _db.connection() as conn:
            with conn.cursor() as cur:
                cur.execute('SELECT "TraineeID" FROM "Applications" WHERE "ApplicationID"=%s', (record_id,)) if record_id else None
                existing = cur.fetchone() if record_id else None
                trainee_id = existing[0] if existing else None
                if trainee_id:
                    cur.execute('UPDATE "Trainees" SET "FullName"=%s,"EmailAddress"=%s,"PhoneNumber"=%s,"PostalCode"=%s,"StateOfResidence"=%s WHERE "TraineeID"=%s', (_v(data.get('Full Name')) or 'Unknown trainee',_v(data.get('Email')),_v(data.get('Phone')),_v(data.get('Postal Code')),_v(data.get('Province')),trainee_id))
                else:
                    trainee_id = _trainee_id(cur, data.get('Full Name'), data.get('Email'), data.get('Phone'), data.get('Postal Code'), data.get('Province'))
                if record_id:
                    pairs = list(APP_TO_DB.items())
                    cols = ['Timestamp'] + [dbcol for _,dbcol in pairs]
                    vals = [_v(data.get('Timestamp'))] + [_v(data.get(label)) for label,_ in pairs]
                    # Let PostgreSQL cast date/time fields from strings.
                    cur.execute('UPDATE "Applications" SET "Timestamp"=%s, '+','.join(f'"{c}"=%s' for c in cols[1:])+' WHERE "ApplicationID"=%s', vals+[record_id])
                else:
                    cols = ['TraineeID','Timestamp'] + [dbcol for _,dbcol in APP_TO_DB.items()]
                    vals = [trainee_id,_v(data.get('Timestamp'))] + [_v(data.get(label)) for label in APP_TO_DB]
                    cur.execute('INSERT INTO "Applications" ('+','.join(f'"{c}"' for c in cols)+') VALUES ('+','.join(['%s']*len(cols))+')', vals)
    except (DatabaseError, Exception) as exc:
        if isinstance(exc, DataError): raise
        raise DataError(str(exc) if 'duplicate key' in str(exc).lower() else f'Could not save application ({exc.__class__.__name__}). Check required fields and database connection.') from exc


"""PostgreSQL-backed data access and safe CRUD helpers for NEXUS CRM."""
from __future__ import annotations
from datetime import date, datetime
from pathlib import Path

from core.database import Database, DatabaseError

class DataError(Exception):
    """A problem with the local PostgreSQL database or stored data."""

class Table:
    """Headers and display rows, with stable database IDs kept separately."""
    def __init__(self, headers, rows, row_ids=None):
        self.headers = list(headers)
        self.rows = [list(r) for r in rows]
        self.row_ids = list(row_ids) if row_ids is not None else list(range(len(self.rows)))
    def index(self, name: str) -> int:
        wanted = name.strip().casefold()
        for i, header in enumerate(self.headers):
            if str(header).strip().casefold() == wanted: return i
        return -1

_db = Database()
_schema_ready = False

def _display(value):
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M") if value.hour or value.minute else value.strftime("%Y-%m-%d")
    if isinstance(value, date): return value.isoformat()
    return value

def _rows_to_table(headers, records, id_key=None):
    ids = [r.get(id_key) for r in records] if id_key else None
    return Table(headers, [[_display(r.get(h)) for h in headers] for r in records], ids)

def ensure_extended_schema():
    """Add fields omitted by the starter schema without dropping or truncating data."""
    global _schema_ready
    if _schema_ready: return
    app_columns = {
        "ReasonsForApplyingToVIT": "TEXT", "MentorMeeting": "TEXT", "GreenCheck": "TEXT",
        "InternalTracking1": "TEXT", "InternalTracking2": "TEXT", "InternalTracking3": "TEXT",
        "ProcessingStatus": "TEXT",
    }
    mentor_columns = {"VITGroup": "TEXT", "SecondaryScore": "TEXT"}
    try:
        with _db.connection() as conn:
            with conn.cursor() as cur:
                cur.execute('''SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='Applications' ''')
                existing_app = {r[0] for r in cur.fetchall()}
                cur.execute('''SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='Mentors' ''')
                existing_mentor = {r[0] for r in cur.fetchall()}
                new_app = set(app_columns) - existing_app
                new_mentor = set(mentor_columns) - existing_mentor
                for col, typ in app_columns.items():
                    cur.execute(f'ALTER TABLE "Applications" ADD COLUMN IF NOT EXISTS "{col}" {typ}')
                for col, typ in mentor_columns.items():
                    cur.execute(f'ALTER TABLE "Mentors" ADD COLUMN IF NOT EXISTS "{col}" {typ}')
                cur.execute('''CREATE TABLE IF NOT EXISTS "VITHistory" (
                    "VITHistoryID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "VITGroup" TEXT, "CandidateName" TEXT, "Email" TEXT)''')
                cur.execute('''CREATE TABLE IF NOT EXISTS "AppSchemaMigrations" (
                    "MigrationKey" TEXT PRIMARY KEY, "AppliedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW())''')
                cur.execute('SELECT 1 FROM "AppSchemaMigrations" WHERE "MigrationKey"=%s', ('extended_fields_v2',))
                needs_backfill = cur.fetchone() is None
                # Backfill once only; never overwrite a user's later edits on subsequent launches.
                # Fill only NULL optional fields from the supplied workbook when row counts match.
                # This is safe on both old and already-migrated databases and never overwrites edits.
                cur.execute('SAVEPOINT optional_backfill')
                if needs_backfill:
                    try:
                        from openpyxl import load_workbook
                        root = Path(__file__).resolve().parent.parent
                        app_path, mentor_path = root/'data'/'Applications.xlsx', root/'data'/'Mentor.xlsx'
                        if app_path.exists():
                            wb = load_workbook(app_path, read_only=True, data_only=True)
                            ws = wb['Applications']; it = ws.iter_rows(values_only=True); headers = [str(x).strip() if x is not None else '' for x in next(it)]
                            source = [dict(zip(headers, r)) for r in it if any(v is not None for v in r)]
                            cur.execute('SELECT "ApplicationID" FROM "Applications" ORDER BY "ApplicationID"')
                            ids = [r[0] for r in cur.fetchall()]
                            if len(ids) == len(source):
                                mapping = {
                                    'ReasonsForApplyingToVIT': 'Reasons for Applying to VIT', 'MentorMeeting': 'Mentor Meeting',
                                    'GreenCheck': 'Green Check', 'InternalTracking1': 'Internal Tracking 1',
                                    'InternalTracking2': 'Internal Tracking 2', 'InternalTracking3': 'Internal Tracking 3',
                                    'ProcessingStatus': 'Processing Status'}
                                for aid, row in zip(ids, source):
                                    for col, source_col in mapping.items():
                                        if col in app_columns:
                                            value = row.get(source_col)
                                            cur.execute(f'UPDATE "Applications" SET "{col}"=%s WHERE "ApplicationID"=%s AND "{col}" IS NULL', (None if value is None else str(value), aid))
                            wb.close()
                        if mentor_path.exists():
                            wb = load_workbook(mentor_path, read_only=True, data_only=True)
                            ws = wb['Mentor']; it = ws.iter_rows(values_only=True); headers = [str(x).strip() if x is not None else '' for x in next(it)]
                            source = [dict(zip(headers, r)) for r in it if any(v is not None for v in r)]
                            cur.execute('SELECT "MentorID" FROM "Mentors" ORDER BY "MentorID"')
                            ids = [r[0] for r in cur.fetchall()]
                            if len(ids) == len(source):
                                for mid, row in zip(ids, source):
                                    for col, source_col in {'VITGroup':'VIT Group','SecondaryScore':'Secondary Score'}.items():
                                        if col in mentor_columns:
                                            value = row.get(source_col)
                                            cur.execute(f'UPDATE "Mentors" SET "{col}"=%s WHERE "MentorID"=%s AND "{col}" IS NULL', (None if value is None else str(value), mid))
                            # Seed the VIT history sheet only if the new table is empty.
                            cur.execute('SELECT COUNT(*) FROM "VITHistory"'); count = cur.fetchone()[0]
                            if count == 0 and 'VIT History' in wb.sheetnames:
                                ws_hist = wb['VIT History']; hist = ws_hist.iter_rows(values_only=True); hh = [str(x).strip() if x is not None else '' for x in next(hist)]
                                for row in hist:
                                    item = dict(zip(hh, row))
                                    if item.get('Candidate Name'):
                                        cur.execute('INSERT INTO "VITHistory" ("VITGroup","CandidateName","Email") VALUES (%s,%s,%s)', (item.get('VIT Group'), item.get('Candidate Name'), item.get('Email')))
                            wb.close()
                    except Exception:
                        # Schema changes remain useful even if an optional workbook backfill is unavailable.
                        pass
                        cur.execute('ROLLBACK TO SAVEPOINT optional_backfill')
                cur.execute('RELEASE SAVEPOINT optional_backfill')
                # Also seed VIT history when the schema was already extended by a manual SQL run.
                try:
                    cur.execute('SAVEPOINT vit_history_seed')
                    cur.execute('SELECT COUNT(*) FROM "VITHistory"')
                    if cur.fetchone()[0] == 0:
                        from openpyxl import load_workbook
                        mentor_path = Path(__file__).resolve().parent.parent / 'data' / 'Mentor.xlsx'
                        if mentor_path.exists():
                            wb_hist = load_workbook(mentor_path, read_only=True, data_only=True)
                            if 'VIT History' in wb_hist.sheetnames:
                                ws_hist = wb_hist['VIT History']; it_hist = ws_hist.iter_rows(values_only=True)
                                hh = [str(x).strip() if x is not None else '' for x in next(it_hist)]
                                for row in it_hist:
                                    item = dict(zip(hh, row))
                                    if item.get('Candidate Name'):
                                        cur.execute('INSERT INTO "VITHistory" ("VITGroup","CandidateName","Email") VALUES (%s,%s,%s)', (item.get('VIT Group'), item.get('Candidate Name'), item.get('Email')))
                            wb_hist.close()
                except Exception:
                    pass
                    cur.execute('ROLLBACK TO SAVEPOINT vit_history_seed')
                cur.execute('RELEASE SAVEPOINT vit_history_seed')
                cur.execute('INSERT INTO "AppSchemaMigrations" ("MigrationKey") VALUES (%s) ON CONFLICT DO NOTHING', ('extended_fields_v2',))
        _schema_ready = True
    except DatabaseError as exc:
        raise DataError(str(exc)) from exc

